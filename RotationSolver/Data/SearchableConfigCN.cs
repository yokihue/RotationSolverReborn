            if (_nameTranslations.TryGetValue(englishName, out var chinese))
            {
                return chinese;
            }
            return englishName;
        }

        /// <summary>
        /// Gets the Chinese translation for a UI config description.
        /// Returns the English original if no translation exists.
        /// </summary>
        public static string TryGetDescription(string englishDesc)
        {
            if (_descTranslations.TryGetValue(englishDesc, out var chinese))
            {
                return chinese;
            }

            // C# escape sequences like \r\n in source become actual CR+LF at runtime,
            // but our dictionary keys use the literal text. Normalize and retry.
            var normalized = englishDesc.Replace("\r\n", "\\r\\n");
            if (normalized != englishDesc && _descTranslations.TryGetValue(normalized, out chinese))
            {
                return chinese;
            }

            return englishDesc;
        }
    }
